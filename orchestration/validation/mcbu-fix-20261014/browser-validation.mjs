import { createRequire } from 'node:module';
import { readFileSync,writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require(resolve('orchestration/tools/node_modules/playwright'));
const fixture=JSON.parse(readFileSync('orchestration/specs/mcbu-tip-uzmanlik.fixture.json','utf8'));
fixture.researchData.thesis.values.THESIS_TITLE_EN='';
fixture.content=fixture.content.replace('<h1>Genel Bilgiler</h1>','<h1>Yanlış Başlık</h1>').replace(/\(1\)/g,'(Karasar, 2020)');
fixture.researchData.thesis.sectionContent.bibliography='<p>Karasar (2020). Numarasız kaynak.</p>';
fixture.researchData.thesis.sectionContent.preface=Array.from({length:12},()=>`<p>${'Kontrollü önsöz sayfa sınırı denemesi. '.repeat(22)}</p>`).join('');
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--enable-blink-features=MulticolColumnWrapping']});
try {
  const context=await browser.newContext({viewport:{width:1400,height:1000}});
  await context.grantPermissions(['local-fonts'],{origin:'http://127.0.0.1:5175'});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await context.addInitScript(value=>localStorage.setItem('txtnote-thesis-regression',value),JSON.stringify(fixture));
  await page.goto('http://127.0.0.1:5175/tests/thesis.html');
  await page.waitForFunction(()=>document.querySelector('[aria-label="Belge sayfaları"]')?.dataset.thesisPaginationReady==='true',null,{timeout:120000});
  const warnings=page.locator('details').filter({has:page.locator('summary').filter({hasText:/belge uyarısı/})});
  await warnings.locator('summary').click();
  const text=await warnings.innerText();
  const expected=['İngilizce özette kullanılacak İngilizce tez başlığını','Eksik ana bölümler: GENEL BİLGİLER','yazar-yıl biçimindeki atıfları','Kaynakça girdilerini','ÖNSÖZ: kılavuz en fazla 1 sayfa'];
  const checks=expected.map(message=>({message,shown:text.includes(message)}));
  await page.screenshot({path:'orchestration/validation/mcbu-fix-20261014/browser-validation.png'});
  const result={checks,errors,pass:checks.every(check=>check.shown)&&errors.length===0};
  writeFileSync('orchestration/validation/mcbu-fix-20261014/browser-validation.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
  if (!result.pass) process.exitCode=1;
} finally {await browser.close();}
