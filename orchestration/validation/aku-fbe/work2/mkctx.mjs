// context matrix for equations/headings/captions: node mkctx.mjs <registryId> <out.json> [tallLatex]
import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
const [rid, out] = process.argv.slice(2);
const SP = process.env.SP; const ROOT = "/home/user/TxtNote-Template-Work";
const base = JSON.parse(await readFile(`${SP}/x/${rid}.fixture.json`, "utf8"));
const IMAGE = base.content.match(/src="(data:image\/png;base64,[^"]+)"/)[1];
const P = (t) => `<p>${t}</p>`;
const PB = `<div class="academic-page-break" data-academic-page-break="true"></div>`;
const fn = (id, text) => `<sup class="academic-footnote" contenteditable="false" data-fn-id="${id}" data-fn-text="${text}">1</sup>`;
const figure = (cap) => `<figure class="academic-figure" data-kind="figure" contenteditable="false"><img width="420" height="210" src="${IMAGE}" alt=""><figcaption>${cap}</figcaption></figure>`;
const table = (cap) => `<div class="academic-table-wrap" data-academic-table="true"><table class="academic-table" data-kind="table"><caption>${cap}</caption><thead><tr><th>A</th><th>B</th></tr></thead><tbody><tr><td>1</td><td>2</td></tr><tr><td>3</td><td>4</td></tr></tbody></table></div>`;
const eq = (latex, num = true) => `<span class="math-formula math-formula--block" data-display="block" data-latex="${latex}"${num ? ' data-eq-numbered="true"' : ""}>(${latex})</span>`;
const note = (t) => `<p data-thesis-style="tableNote">${t}</p>`;
const c = [];
c.push(`<h1>Baglam Matrisi</h1>`);
c.push(P("A1 onceki paragraf."), eq("qa = pa"), P("A2 sonraki paragraf."), PB);
c.push(`<h2>B baslik</h2>`, eq("qb = pb"), P("B2 sonraki paragraf."), PB);
c.push(P("C1 onceki paragraf."), eq("qc = pc"), eq("qd = pd"), P("C2 sonraki paragraf."), PB);
c.push(P("D1 onceki paragraf."), figure("D sekil basligi"), eq("qe = pe"), P("D2 sonraki paragraf."), PB);
c.push(P("E1 onceki paragraf."), table("E tablo notsuz"), eq("qf = pf"), P("E2 sonraki paragraf."), PB);
c.push(P("F1 onceki paragraf."), table("F tablo notlu"), note("Not: F notu."), eq("qg = pg"), P("F2 sonraki paragraf."), PB);
c.push(P("G1 onceki paragraf."), eq("qh = ph"), `<h2>G baslik</h2>`, P("G2 sonraki paragraf."), PB);
c.push(P("H1 onceki paragraf."), eq("qi = pi"), figure("H sekil basligi"), P("H2 sonraki paragraf."), PB);
c.push(P("I1 onceki paragraf."), eq("qj = pj"), table("I tablo"), P("I2 sonraki paragraf."), PB);
c.push(eq("qk = pk"), P("K2 sayfa basi denklem sonrasi paragraf."), PB);
c.push(`<ul><li>M liste 1</li><li>M liste 2</li></ul>`, eq("ql = pl"), P("M2 sonraki paragraf."), PB);
c.push(P("N1 onceki paragraf."), eq("qm = pm"), `<ul><li>N liste 1</li><li>N liste 2</li></ul>`, P("N2 sonraki paragraf."), PB);
c.push(P(`O1 dipnotlu paragraf${fn("o1", "O notu bir")}${fn("o2", "O notu iki")}.`), eq("qn = pn"), P("O2 sonraki paragraf."), PB);
c.push(P("P1 onceki paragraf."), eq("qo = po"), note("Not: P notu (tabloya bagli olmayan)."), P("P2 sonraki paragraf."), PB);
c.push(P("Q1 onceki paragraf."), eq("q = \\frac{a}{b}"), P("Q2 sonraki paragraf."), PB);
c.push(P("R1 onceki paragraf."), eq("q = \\sum_{i=1}^{n} x_i"), P("R2 sonraki paragraf."), PB);
c.push(`<h1>Ikinci Bolum</h1>`, eq("qs = ps"), P("S2 ikinci bolum denklem sonrasi."));
const ov = { title: "Kısa Başlık", content: c.join("") };
await writeFile(`${SP}/adv/ovctx.json`, JSON.stringify(ov));
execFileSync("node", [`${ROOT}/orchestration/tools/make-fixture.mjs`, rid, out, `${SP}/adv/ovctx.json`], { stdio: "inherit" });
