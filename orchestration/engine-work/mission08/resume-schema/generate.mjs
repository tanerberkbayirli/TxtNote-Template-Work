const require = createRequire(new URL('../../../../TxtNote/frontend/package.json', import.meta.url));
const { unzipSync, strFromU8 } = require('fflate');
const directory = new URL('.//', import.meta.url);
mkdirSync(directory, { recursive: true });
const cases = [];
const write = async (name, model, options = {}, check = () => {}) => {
  const blob = await buildThesisDocx(model, options);
  const bytes = new Uint8Array(await blob.arrayBuffer());
  const files = unzipSync(bytes);
  check(Object.fromEntries(Object.entries(files).filter(([path]) => path.endsWith('.xml')).map(([path, data]) => [path, strFromU8(data)])));
  writeFileSync(new URL(`${name}.docx`, directory), bytes);
  cases.push({ name, bytes: bytes.length });
};
const compile = (html, template = generic) => compileThesisDocument(structuredClone(template), {}, 'Bağımsız şema deneyi', html);
await write('bold-italic', compile('<h1>Kalın başlık</h1><p><strong>Kalın</strong> <em>İtalik</em> <strong><em>İkisi</em></strong> <u>Alt çizgi</u></p>'), {}, (files) => {
  assert.match(files['word/document.xml'], /<w:b/); assert.match(files['word/document.xml'], /<w:i/);
});
const imported = await importThesisDocx(docxImportFixture({ body: '<w:p><w:bookmarkStart w:id="12" w:name="ImportedTarget"/><w:r><w:t>Yer işareti</w:t></w:r><w:bookmarkEnd w:id="12"/></w:p><w:p><w:r><w:rPr><w:b/><w:i/></w:rPr><w:t>Kalın italik</w:t></w:r></w:p>' }));
const importedDoc = installContentDocument({ title: 'Yer işaretleri', content: '', researchData: { thesis: { templateId: generic.id } } }, imported);
await write('imported-bookmark', compileThesisDocument(generic, importedDoc.researchData.thesis, importedDoc.title, importedDoc.content), {}, (files) => assert.match(files['word/document.xml'], /w:name="ImportedTarget"/));
await write('table-widths', compile('<table><colgroup><col data-col-width="25"><col data-col-width="75"></colgroup><thead><tr><th>Başlık A</th><th>Başlık B</th></tr></thead><tbody><tr><td>A</td><td>B</td></tr></tbody></table>'), {}, (files) => assert.match(files['word/document.xml'], /<w:tblW/));
const note = (kind, id, text) => `<sup class="academic-${kind}" contenteditable="false" data-fn-id="${id}" data-fn-text="${text}" data-fn-index="1">1</sup>`;
