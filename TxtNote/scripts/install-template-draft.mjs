#!/usr/bin/env node
// Install a template draft (docx-spec-to-template.py output) as a generated template module
// and refresh the generated registry index that registry.js imports.
//   node scripts/install-template-draft.mjs output/template-drafts/<id>.draft.json [--status official|generic]
// Writes frontend/src/thesis/templates/generated/<id>.js (export default {...template}) and
// generated/index.js (descriptors with dynamic loaders). Generated modules are data; they are
// validated at load time like every other template.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const generatedDir = path.join(here, "..", "frontend", "src", "thesis", "templates", "generated");
const args = process.argv.slice(2);
const statusIndex = args.indexOf("--status");
const statusOverride = statusIndex >= 0 ? args[statusIndex + 1] : null;
const files = args.filter((arg, index) => !arg.startsWith("--") && index !== statusIndex + 1);
if (!files.length) { console.error("kullanım: install-template-draft.mjs <draft.json> [...]"); process.exit(2); }
fs.mkdirSync(generatedDir, { recursive: true });

for (const file of files) {
  const draft = JSON.parse(fs.readFileSync(file, "utf8"));
  const template = draft.template ?? draft;
  if (statusOverride) template.status = statusOverride;
  if (!template.id) throw new Error(`${file}: template.id yok`);
  const safe = template.id.replace(/[^a-z0-9-]/gi, "-");
  const target = path.join(generatedDir, `${safe}.js`);
  const header = `// Generated by scripts/install-template-draft.mjs from ${path.basename(file)} — do not edit by hand.\n// Source: ${template.source?.documentName || template.source?.url || "?"} · unknown fields: ${draft.unknown?.length ?? 0} · inferred: ${draft.inferred?.length ?? 0}\n`;
  fs.writeFileSync(target, `${header}export default ${JSON.stringify(template, null, 1)};\n`);
  console.log(`${template.id} → ${path.relative(process.cwd(), target)} (${(fs.statSync(target).size / 1024).toFixed(0)} KB)`);
}

// Rebuild the index from every generated module.
const modules = fs.readdirSync(generatedDir).filter((name) => name.endsWith(".js") && name !== "index.js").sort();
const entries = [];
for (const name of modules) {
  const source = fs.readFileSync(path.join(generatedDir, name), "utf8");
  const json = source.slice(source.indexOf("export default ") + "export default ".length).replace(/;\s*$/, "");
  const t = JSON.parse(json);
  const descriptor = { id: t.id, templateVersion: t.templateVersion, universityId: t.universityId, universityName: t.universityName, instituteId: t.instituteId, instituteName: t.instituteName, degreeType: t.degreeType, language: t.language, status: t.status, displayName: `${t.universityName} · ${t.instituteName || ""} · ${t.degreeType === "phd" ? "Doktora" : "Yüksek Lisans"}${t.status === "official" ? "" : " (taslak)"}`.replace(" ·  ·", " ·"), selectors: {} };
  entries.push(`  { ${Object.entries(descriptor).map(([key, value]) => `${key}: ${JSON.stringify(value)}`).join(", ")}, load: () => import("./${name}") },`);
}
fs.writeFileSync(path.join(generatedDir, "index.js"), `// Generated by scripts/install-template-draft.mjs — do not edit by hand.\n/** Descriptors of generated templates; registry.js appends them to the hand-written registry. */\nexport const GENERATED_THESIS_TEMPLATES = Object.freeze([\n${entries.join("\n")}\n]);\n`);
console.log(`${entries.length} üretilmiş şablon → generated/index.js`);
